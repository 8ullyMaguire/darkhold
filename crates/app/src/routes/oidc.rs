//! Sign in with Polaris (W2).
//!
//! ```text
//! GET /api/v1/auth/oidc/start      → 303 to polaris-id /authorize (state + PKCE + nonce)
//! GET /api/v1/auth/oidc/callback   → 303 back into the site, with a local session
//! ```
//!
//! The protocol is `polaris-oidc-client` — PKCE+state+nonce, the authorize URL, the two provider calls,
//! the claim checks — shared with gravity and (next) whitebois. What stays here is what is darkhold's: where
//! the attempt is parked, which account a subject maps to, and the session this site issues.
//!
//! Three rules, each of which is the reason this is server-side rather than a script on the login page:
//!
//! * **The verifier never reaches the browser.** State, PKCE verifier and nonce are generated by the crate
//!   and parked in `oidc_pending` for ten minutes; the callback redeems them with `DELETE … RETURNING`, so
//!   a replayed callback finds nothing instead of minting a second session.
//! * **Links are by verified email, never by handle.** Handles are per-pseud on this site and the estate is
//!   deliberately not a single namespace; an email the provider says it verified is evidence, a handle is
//!   a coincidence.
//! * **An unknown email is not an account.** It bounces to `/login?oidc=no_account` rather than creating
//!   one, because account creation here is a product decision (ages, pseuds, consent) and not something a
//!   redirect handler should decide.
//!
//! Adopting the crate closed a gap this file had: it minted a nonce and never checked it. `verify_claims`
//! now checks the nonce, the audience and the issuer against the id_token the token endpoint handed back.
//!
//! Configuration is three environment variables, read per request so a restart is not needed to see a
//! corrected one: `POLARIS_ID_ISSUER`, `POLARIS_ID_CLIENT_ID`, `POLARIS_ID_REDIRECT_URI`. Unlike gravity,
//! this site treats a missing one as "Polaris sign-in is off" rather than falling back to a default: a
//! deployment that has not been configured should not send people to a host it guessed.

use std::collections::HashMap;

use axum::extract::{Query, State};
use axum::http::{header, HeaderMap, HeaderValue};
use axum::response::{IntoResponse, Redirect, Response};
use axum::routing::get;
use axum::Router;
use darkhold_db::identity;
use darkhold_db::oidc;
use polaris_oidc_client::{
    decode_jwt_payload, safe_next, urlencode, AuthorizeRequest, OidcConfig, Provider,
};

use crate::auth::{self, CookiePolicy, MaybeSession, CSRF_COOKIE, SESSION_COOKIE};
use crate::state::AppState;

const PROVIDER: &str = "polaris-id";
const SCOPE: &str = "profile:read email";
const PENDING_TTL_SECONDS: i64 = 600;

/// Routes. Mounted inside the auth module, so module gating and the auth rate-limit class apply.
pub fn router() -> Router<AppState> {
    Router::new()
        .route("/auth/oidc/start", get(start))
        .route("/auth/oidc/callback", get(callback))
}

/// `None` when any of the three variables is missing or empty — the module is off, not defaulted.
fn config() -> Option<OidcConfig> {
    let issuer = std::env::var("POLARIS_ID_ISSUER").ok()?;
    let client_id = std::env::var("POLARIS_ID_CLIENT_ID").ok()?;
    let redirect_uri = std::env::var("POLARIS_ID_REDIRECT_URI").ok()?;
    if issuer.is_empty() || client_id.is_empty() || redirect_uri.is_empty() {
        return None;
    }
    Some(OidcConfig::new(issuer, client_id, redirect_uri))
}

fn unavailable() -> Response {
    (
        axum::http::StatusCode::SERVICE_UNAVAILABLE,
        axum::Json(serde_json::json!({
            "error": {"code": "unavailable", "message": "Polaris sign-in is not configured on this site"}
        })),
    )
        .into_response()
}

/// `GET /api/v1/auth/oidc/start?next=/works/12&prompt=none`
async fn start(
    State(state): State<AppState>,
    // Anonymous on purpose, and declared so: a reader who is already signed in may
    // also use this door to link a Polaris identity. The route table in `inventory.rs`
    // reads this extractor, so the type named here is the audience.
    MaybeSession(_session): MaybeSession,
    Query(params): Query<HashMap<String, String>>,
) -> Response {
    let Some(config) = config() else {
        return unavailable();
    };

    let request = AuthorizeRequest::generate(SCOPE);
    let next = safe_next(params.get("next").map(String::as_str).unwrap_or("/"));

    let expires = identity::format_rfc3339(
        time::OffsetDateTime::now_utc() + time::Duration::seconds(PENDING_TTL_SECONDS),
    );

    if let Err(error) = oidc::create_pending(
        state.db(),
        &request.state,
        &request.pkce.verifier,
        &request.nonce,
        &next,
        &expires,
    )
    .await
    {
        tracing::error!(%error, "could not park the OIDC attempt");
        return unavailable();
    }

    // `prompt=none` is what makes silent re-auth safe: if the provider has no session it answers
    // login_required instead of showing a form, and the caller treats that as "anonymous".
    let silent = params.get("prompt").map(String::as_str) == Some("none");
    tracing::info!(next = %next, silent, "starting Polaris sign-in");
    Redirect::to(&request.url(&config, silent)).into_response()
}

/// `GET /api/v1/auth/oidc/callback?code=…&state=…`
async fn callback(
    State(state): State<AppState>,
    // Reached by the provider's redirect, which carries no session of ours — but the
    // account it lands on may be one this browser is already signed into, so the
    // audience is public and the extractor says so.
    MaybeSession(_session): MaybeSession,
    headers: HeaderMap,
    Query(params): Query<HashMap<String, String>>,
) -> Response {
    let Some(config) = config() else {
        return unavailable();
    };

    if let Some(error) = params.get("error") {
        tracing::info!(%error, "the provider refused the sign-in");
        return Redirect::to(&format!("/login?oidc={}", urlencode(error))).into_response();
    }
    let (Some(code), Some(attempt)) = (params.get("code"), params.get("state")) else {
        return Redirect::to("/login?oidc=invalid_response").into_response();
    };

    let now = identity::now_rfc3339();
    let pending = match oidc::take_pending(state.db(), attempt, &now).await {
        Ok(Some(pending)) => pending,
        Ok(None) => {
            tracing::warn!("OIDC callback with an unknown, expired or already-used state");
            return Redirect::to("/login?oidc=expired").into_response();
        }
        Err(error) => {
            tracing::error!(%error, "could not redeem the OIDC attempt");
            return Redirect::to("/login?oidc=error").into_response();
        }
    };

    let provider = Provider::new(config.clone());
    let tokens = match provider.exchange_code(code, &pending.verifier).await {
        Ok(tokens) => tokens,
        Err(error) => {
            tracing::warn!(%error, "token exchange refused");
            return Redirect::to("/login?oidc=error").into_response();
        }
    };
    let Some(access) = tokens.access_token.as_deref() else {
        tracing::error!("token response carried no access token");
        return Redirect::to("/login?oidc=error").into_response();
    };
    // The nonce, the audience and the issuer are checked against the id_token — the three things that bind
    // a token to this attempt. Before the crate, this file sent a nonce and never verified it.
    let verified = match tokens.id_token.as_deref() {
        // `verify_id_token`, not `decode_jwt_payload` + a claims comparison: the crate's 0.2.0 verifies the **signature** against
        // the provider's published JWKS as well as `iss`/`aud`/`exp`/nonce. Reading the payload and checking three fields accepted a
        // token anything on the wire could have written, which is the gap the crate was updated to close — and the reason a claims
        // helper no longer exists to call. The `Provider` is the same value that exchanged the code, so the key set is fetched once.
        Some(id_token) => provider.verify_id_token(id_token, &pending.nonce).await,
        None => {
            tracing::error!(
                "token response carried no id_token, so the attempt cannot be verified"
            );
            return Redirect::to("/login?oidc=invalid_response").into_response();
        }
    };
    let verified = match verified {
        Ok(verified) => verified,
        Err(error) => {
            tracing::warn!(%error, "the identity token did not verify");
            return Redirect::to("/login?oidc=invalid_response").into_response();
        }
    };

    // The issuer's assurance claim for this sign-in, read verbatim and handed to the session. It is decoded from the
    // same token that just verified, and it is never interpreted here: step-up (M70-08) compares it, so this site
    // never has to invent an assurance level of its own.
    let acr = tokens
        .id_token
        .as_deref()
        .and_then(|token| decode_jwt_payload(token).ok())
        .and_then(|claims| {
            claims
                .get("acr")
                .and_then(serde_json::Value::as_str)
                .map(str::to_owned)
        });

    // The roles the issuer asserted, read verbatim from the same verified token and stored on the session (ADR 0003).
    // Not interpreted here: what a role means is polaris-id's `docs/ROLES.md`, and this site's job is to remember it and
    // to check it where a route says which site it belongs to.
    let roles: Vec<String> = tokens
        .id_token
        .as_deref()
        .and_then(|token| decode_jwt_payload(token).ok())
        .and_then(|claims| {
            claims.get("roles").and_then(|v| {
                v.as_array().map(|a| {
                    a.iter()
                        .filter_map(|s| s.as_str().map(str::to_owned))
                        .collect()
                })
            })
        })
        .unwrap_or_default();

    // The profile comes from /userinfo over TLS rather than from the id_token's payload: one authority
    // decides who the user is, and no product has to grow a JWT verifier to find out.
    let profile = match provider.userinfo(access).await {
        Ok(profile) => profile,
        Err(error) => {
            tracing::warn!(%error, "userinfo refused");
            return Redirect::to("/login?oidc=error").into_response();
        }
    };
    if profile.sub.is_empty() || profile.sub != verified.sub {
        tracing::warn!("userinfo subject does not match the verified id_token subject");
        return Redirect::to("/login?oidc=invalid_response").into_response();
    }

    let subject = profile.sub.as_str();
    let handle = profile.handle.as_deref();
    let email = profile.email.as_str();
    let email = (!email.is_empty() && profile.email_verified).then_some(email);
    // Kept beside the link so a page render never has to call the provider: see migration 0148.
    let picture = profile.picture.as_deref();
    let display_name = profile.name.as_deref();

    // 1. An established link wins — it is the only mapping that survives an email change.
    let mut account = match oidc::find_link(state.db(), PROVIDER, subject).await {
        Ok(Some(id)) => {
            // An established link still refreshes the cached profile: a rename at the provider reaches this
            // site on the next sign-in rather than never.
            if let Ok(Some(found)) = identity::find_account(state.db(), id).await {
                let _ = oidc::link(
                    state.db(),
                    PROVIDER,
                    subject,
                    found.id,
                    email,
                    picture,
                    display_name,
                    &now,
                )
                .await;
                Some(found)
            } else {
                None
            }
        }
        _ => None,
    };
    let mut linked_now = false;

    // 2. Otherwise the verified address the provider vouches for.
    if account.is_none() {
        if let Some(email) = email {
            if let Ok(Some(found)) = identity::find_account_by_email(state.db(), email).await {
                if oidc::link(
                    state.db(),
                    PROVIDER,
                    subject,
                    found.id,
                    Some(email),
                    picture,
                    display_name,
                    &now,
                )
                .await
                .is_ok()
                {
                    linked_now = true;
                }
                account = Some(found);
            }
        }
    }

    let Some(account) = account else {
        tracing::info!(
            handle = handle.unwrap_or(""),
            "Polaris sign-in for an account this site does not have"
        );
        return Redirect::to(&format!(
            "/login?oidc=no_account&handle={}",
            urlencode(handle.unwrap_or(""))
        ))
        .into_response();
    };
    if !matches!(account.status, darkhold_db::identity::AccountStatus::Active) {
        tracing::info!(account = %account.id, "Polaris sign-in to a non-active account");
        return Redirect::to("/login?oidc=inactive").into_response();
    }

    let pseuds = identity::pseuds_for_account(state.db(), account.id)
        .await
        .unwrap_or_default();
    let initial = pseuds.first().map(|pseud| pseud.id);
    let user_agent = headers
        .get(header::USER_AGENT)
        .and_then(|value| value.to_str().ok());

    let issued = match auth::issue_session(
        &state,
        &account,
        initial,
        user_agent,
        acr.as_deref(),
        &roles,
    )
    .await
    {
        Ok(issued) => issued,
        Err(error) => {
            tracing::error!(%error, "could not issue a session after Polaris sign-in");
            return Redirect::to("/login?oidc=error").into_response();
        }
    };
    if let Err(error) =
        darkhold_db::engagement::record_login(state.db(), &account.id.to_string()).await
    {
        tracing::warn!(account = %account.id, %error, "failed to record login streak");
    }
    tracing::info!(
        account = %account.id,
        subject = %subject,
        linked_now,
        "signed in with Polaris"
    );

    let policy = CookiePolicy::from_config(state.config());
    let ttl = state.config().security.session_ttl;
    let mut response = Redirect::to(&pending.next).into_response();
    for cookie in [
        auth::build_cookie(SESSION_COOKIE, &issued.token, policy, Some(ttl), true),
        auth::build_cookie(CSRF_COOKIE, &issued.csrf_token, policy, Some(ttl), false),
    ] {
        if let Ok(value) = HeaderValue::from_str(&cookie) {
            response.headers_mut().append(header::SET_COOKIE, value);
        }
    }
    response
}
