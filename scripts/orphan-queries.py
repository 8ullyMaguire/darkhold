#!/usr/bin/env python3
"""Regenerate docs/plans/orphan-queries.txt — the M70-13 ratchet's baseline.

A function is an orphan when nothing outside `crates/db` and outside `tests/` mentions its name. The list is debt, not
permission: it exists so `crates/app/tests/orphan_queries.rs` can fail on a *new* orphan while the existing ones are
worked off. Deleting a line is the goal; adding one needs a reason a reviewer can read.

Usage:
    python3 scripts/orphan-queries.py           # rewrite the file
    python3 scripts/orphan-queries.py --check   # exit 1 when the file is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/plans/orphan-queries.txt"

DECLARED = re.compile(r"^\s*pub async fn ([A-Za-z0-9_]+)", re.MULTILINE)


def sources(path: Path, *, skip_db: bool) -> list[str]:
    out: list[str] = []
    for file in sorted(path.rglob("*.rs")):
        if "tests" in file.parts:
            continue
        out.append(file.read_text(encoding="utf-8", errors="replace"))
    return out


def main() -> int:
    declared: list[tuple[str, str]] = []
    for file in sorted((ROOT / "crates/db/src").rglob("*.rs")):
        text = file.read_text(encoding="utf-8", errors="replace")
        for name in DECLARED.findall(text):
            declared.append((name, str(file.relative_to(ROOT))))

    reachable: list[str] = []
    for crate in sorted((ROOT / "crates").iterdir()):
        if not crate.is_dir() or crate.name == "db":
            continue
        src = crate / "src"
        if src.is_dir():
            reachable.extend(sources(src, skip_db=True))
    blob = "\n".join(reachable)

    orphans = []
    for name, file in declared:
        if re.search(rf"(?<![A-Za-z0-9_]){re.escape(name)}(?![A-Za-z0-9_])", blob):
            continue
        orphans.append((name, file))

    header = [
        "# M70-13 ratchet baseline. Generated by scripts/orphan-queries.py — do not hand-edit the names.",
        "#",
        "# Each line is a `pub async fn` in crates/db/src that nothing outside crates/db (and outside tests) mentions.",
        "# They are debt, not permission: crates/app/tests/orphan_queries.rs fails when a NEW one appears, so this list",
        "# can only shrink. Delete a line by wiring the function to a route or deleting the function.",
        f"# measured {__import__('datetime').date.today().isoformat()}: {len(orphans)} orphan(s)",
        "",
    ]
    body = [f"{name}  # {file}" for name, file in orphans]
    text = "\n".join(header + body) + "\n"

    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/plans/orphan-queries.txt is out of date; run python3 scripts/orphan-queries.py")
            return 1
        print(f"ok: {len(orphans)} orphan(s), file current")
        return 0

    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(orphans)} orphan(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
